CREATE EXTENSION IF NOT EXISTS timescaledb;
---
CREATE TABLE IF NOT EXISTS workers (
  wallet text PRIMARY KEY,
  trust_score real NOT NULL DEFAULT 60,
  labels_total int NOT NULL DEFAULT 0,
  labels_approved int NOT NULL DEFAULT 0,
  lamports_earned bigint NOT NULL DEFAULT 0,
  paused boolean NOT NULL DEFAULT false,
  last_answer text,
  streak int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
---
CREATE TABLE IF NOT EXISTS task_sets (
  id text PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('text','pairwise','image')),
  title text NOT NULL,
  guidelines text NOT NULL,
  options jsonb NOT NULL,
  pay_lamports bigint NOT NULL,
  min_latency_ms int NOT NULL DEFAULT 1500
);
---
CREATE TABLE IF NOT EXISTS tasks (
  id text PRIMARY KEY,
  set_id text NOT NULL REFERENCES task_sets(id) ON DELETE CASCADE,
  payload jsonb NOT NULL,
  gold_label text,
  is_gold boolean NOT NULL DEFAULT false
);
---
CREATE INDEX IF NOT EXISTS tasks_set_idx ON tasks(set_id);
---
CREATE TABLE IF NOT EXISTS nonces (
  nonce text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()
);
---
CREATE TABLE IF NOT EXISTS label_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  ts timestamptz NOT NULL DEFAULT now(),
  worker text NOT NULL,
  task_id text NOT NULL,
  set_id text NOT NULL,
  task_type text NOT NULL,
  answer text NOT NULL,
  latency_ms int NOT NULL,
  verdict text NOT NULL,
  confidence real,
  reason text,
  flags jsonb NOT NULL DEFAULT '[]'::jsonb,
  pay_lamports bigint NOT NULL DEFAULT 0,
  trust_after real,
  judge_ms int,
  judge_model text,
  PRIMARY KEY (id, ts)
);
