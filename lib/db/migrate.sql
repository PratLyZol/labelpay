DROP MATERIALIZED VIEW IF EXISTS labels_1m CASCADE;
---
CREATE MATERIALIZED VIEW IF NOT EXISTS labels_1m
WITH (timescaledb.continuous) AS
SELECT
  time_bucket('1 minute', ts) AS bucket,
  task_type,
  count(*) AS labels,
  count(*) FILTER (WHERE verdict = 'approve') AS approved,
  count(*) FILTER (WHERE verdict = 'reject') AS rejected,
  count(*) FILTER (WHERE verdict = 'uncertain') AS uncertain,
  sum(pay_lamports) AS lamports,
  avg(latency_ms) AS avg_latency_ms,
  avg(judge_ms) AS avg_judge_ms,
  count(*) FILTER (WHERE flags ? 'too_fast') AS too_fast,
  count(*) FILTER (WHERE flags ? 'straight_lining') AS straight_lining,
  count(*) FILTER (WHERE flags ? 'gold_miss') AS gold_miss,
  count(*) FILTER (WHERE flags ? 'incoherent') AS incoherent,
  count(*) FILTER (WHERE flags ? 'consensus_disagree') AS consensus_disagree
FROM label_events
GROUP BY bucket, task_type
WITH NO DATA;
---
SELECT add_continuous_aggregate_policy('labels_1m',
  start_offset => INTERVAL '1 day',
  end_offset => INTERVAL '10 seconds',
  schedule_interval => INTERVAL '30 seconds',
  if_not_exists => TRUE);
---
DROP MATERIALIZED VIEW IF EXISTS worker_1m CASCADE;
---
CREATE MATERIALIZED VIEW IF NOT EXISTS worker_1m
WITH (timescaledb.continuous) AS
SELECT
  time_bucket('1 minute', ts) AS bucket,
  worker,
  count(*) AS labels,
  count(*) FILTER (WHERE verdict = 'approve') AS approved,
  sum(pay_lamports) AS lamports,
  avg(trust_after) AS avg_trust,
  last(trust_after, ts) AS trust,
  avg(latency_ms) AS avg_latency_ms
FROM label_events
GROUP BY bucket, worker
WITH NO DATA;
---
SELECT add_continuous_aggregate_policy('worker_1m',
  start_offset => INTERVAL '1 day',
  end_offset => INTERVAL '10 seconds',
  schedule_interval => INTERVAL '30 seconds',
  if_not_exists => TRUE);
